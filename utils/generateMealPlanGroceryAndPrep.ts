/**
 * Build grocery_list (JSON) and prep_guide (text) from PlannedMeals + FoodItems
 * (or MealPlanItems) and persist on MealPlans. Used by MealPlanList and MealPlanDetail.
 *
 * Food categorization: contains-match keyword tables (longest phrases first). Pantry is checked
 * before dairy/meat & fish/produce so oils, condiments, and plant milks map to Pantry.
 */

/** Internal prep buckets; `grain` historically = pantry / grains / dry goods. */
type FoodKind = 'grain' | 'dairy' | 'meatFish' | 'produce' | 'other';

function sortKeywordsLongestFirst(keywords: readonly string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const k of keywords) {
    const t = k.toLowerCase().trim();
    if (t && !seen.has(t)) {
      seen.add(t);
      out.push(t);
    }
  }
  return out.sort((a, b) => b.length - a.length);
}

/**
 * Multi-word phrases: substring match. Single words: delimiter-aware match so we don't hit
 * substrings like pea→pear, tuna→fortuna, oil→boil, beef→beefsteak.
 */
function matchesKeyword(haystackLower: string, keyword: string): boolean {
  const kw = keyword.toLowerCase();
  if (kw.includes(' ')) {
    return haystackLower.includes(kw);
  }
  const escaped = kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`(^|[^a-z0-9])${escaped}([^a-z0-9]|$)`, 'i');
  return re.test(haystackLower);
}

