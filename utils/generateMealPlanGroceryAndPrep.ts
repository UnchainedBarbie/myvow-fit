function categorizeFood(name: string): FoodKind {
  const n = name.toLowerCase();
  for (const kw of PANTRY_KEYWORDS) {
    if (matchesKeyword(n, kw)) return 'grain';
  }
  for (const kw of DAIRY_KEYWORDS) {
    if (matchesKeyword(n, kw)) return 'dairy';
  }
  for (const kw of PROTEIN_KEYWORDS) {
    if (matchesKeyword(n, kw)) return 'meatFish';
  }
  for (const kw of PRODUCE_KEYWORDS) {
    if (matchesKeyword(n, kw)) return 'produce';
  }
  return 'other';
}

function groceryCategoryFromFood(foodName: string): string {
  const kind = categorizeFood(foodName);
  const map: Record<string, string> = {
    grain: 'Pantry',
    meatFish: 'Meat & Fish',
    produce: 'Produce',
    dairy: 'Dairy',
    other: 'Other',
  };
  return map[kind] ?? 'Other';
}

export async function generateGroceryListFromPlan(db: any, planId: number): Promise<void> {
  let rows: { meal_type: string; food_name: string; brand?: string | null; serving_size?: string | null }[] =
    await db
      .getAllAsync(
        `SELECT pm.meal_type, fi.food_name, fi.brand, fi.serving_size
     FROM PlannedMeals pm
     JOIN FoodItems fi ON fi.meal_id = pm.meal_id
     WHERE pm.meal_plan_id = ?
     ORDER BY pm.meal_order, fi.food_id`,
        [planId],
      )
      .catch(() => []);
  if (rows.length === 0) {
    const fallback = (await db
      .getAllAsync(
        'SELECT meal_type, food_name FROM MealPlanItems WHERE meal_plan_id = ? ORDER BY sort_order, item_id',
        [planId],
      )
      .catch(() => [])) as { meal_type: string | null; food_name: string }[];
    rows = fallback.map((r) => ({ meal_type: r.meal_type || 'Other', food_name: r.food_name }));
  }
  const seen = new Set<string>();
  const byCategory: Record<string, string[]> = {
    Produce: [],
    'Meat & Fish': [],
    Dairy: [],
    Pantry: [],
    Other: [],
  };
  for (const r of rows) {
    const item = r.food_name + (r.serving_size ? ` — ${r.serving_size}` : '');
    if (seen.has(item)) continue;
    seen.add(item);
    const cat = groceryCategoryFromFood(r.food_name);
    if (byCategory[cat]) byCategory[cat].push(item);
    else byCategory['Other'].push(item);
  }
  const list: { category: string; item: string; checked: boolean }[] = [];
  for (const cat of ['Produce', 'Meat & Fish', 'Dairy', 'Pantry', 'Other']) {
    for (const item of byCategory[cat]) list.push({ category: cat, item, checked: false });
  }
  await db.runAsync('UPDATE MealPlans SET grocery_list = ? WHERE meal_plan_id = ?', [
    JSON.stringify(list),
    planId,
  ]);
}

/** Case-insensitive dedupe of food names; keeps first-seen casing. */
export function dedupeFoodNamesCaseInsensitive(names: string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of names) {
    if (raw == null) continue;
    const t = String(raw).trim();
    if (!t) continue;
    const k = t.toLowerCase();
    if (seen.has(k)) continue;
    seen.add(k);
    out.push(t);
  }
  return out;
}

/**
 * Build prep guide text from raw food names (deduped case-insensitively),
 * using the same category buckets as per-plan prep (grain/pantry, meat & fish, produce, dairy, other).
 */
export function buildPrepGuideTextFromUniqueFoodNames(names: string[]): string {
  const uniqueFoods = dedupeFoodNamesCaseInsensitive(names);
  if (uniqueFoods.length === 0) return '';

  const byCategory: Record<string, string[]> = {
    grain: [],
    meatFish: [],
    produce: [],
    dairy: [],
    other: [],
  };
  for (const name of uniqueFoods) {
    const cat = categorizeFood(name);
    byCategory[cat].push(name);
  }
  const steps: string[][] = [];
  if (byCategory.grain.length > 0) {
    steps.push([
      'Pantry, grains & dry goods',
      `Stock and prep shelf-stable items and starches: ${byCategory.grain.join(', ')}. Portion where helpful; store per label.`,
    ]);
  }
  if (byCategory.meatFish.length > 0) {
    steps.push([
      'Cook & portion meat & fish',
      `Prep and cook: ${byCategory.meatFish.join(', ')}. Portion into containers for each meal so you can grab and go.`,
    ]);
  }
  if (byCategory.produce.length > 0) {
    steps.push([
      'Wash and chop produce',
      `Wash, dry, and chop: ${byCategory.produce.join(', ')}. Store in containers or bags. Pre-portion for snacks if needed.`,
    ]);
  }
  if (byCategory.dairy.length > 0) {
    steps.push([
      'Portion dairy',
      `Portion out ${byCategory.dairy.join(', ')} into single-serving containers or add to meal containers as needed.`,
    ]);
  }
  steps.push([
    'Portion snacks and breakfast items',
    'Portion out any grab-and-go snacks. Prep overnight oats, egg muffins, or other breakfast items so mornings are easy.',
  ]);
  steps.push([
    'Assemble and store',
    "Label containers by day or meal (e.g. Mon Lunch, Tue Dinner). Keep in the fridge; freeze any portions you won't use within 3–4 days.",
  ]);
  const lines: string[] = ['Meal prep for the week — follow these steps in order.', ''];
  steps.forEach(([title, body], i) => {
    lines.push(`${i + 1}. ${title}`);
    lines.push(`   ${body}`);
    lines.push('');
  });
  lines.push(
    'Your plan includes: ' + uniqueFoods.slice(0, 12).join(', ') + (uniqueFoods.length > 12 ? '...' : '.'),
  );
  return lines.join('\n').trim();
}

export async function generatePrepGuideFromPlan(db: any, planId: number): Promise<void> {
  let rows: { meal_type: string; food_name: string }[] = await db
    .getAllAsync(
      `SELECT pm.meal_type, fi.food_name
     FROM PlannedMeals pm
     JOIN FoodItems fi ON fi.meal_id = pm.meal_id
     WHERE pm.meal_plan_id = ?
     ORDER BY pm.meal_order, fi.food_id`,
      [planId],
    )
    .catch(() => []);
  if (rows.length === 0) {
    rows = (await db
      .getAllAsync(
        'SELECT meal_type, food_name FROM MealPlanItems WHERE meal_plan_id = ? ORDER BY sort_order, item_id',
        [planId],
      )
      .catch(() => [])) as { meal_type: string | null; food_name: string }[];
    rows = rows.map((r) => ({ meal_type: r.meal_type || 'Meal', food_name: r.food_name }));
  }
  const text = buildPrepGuideTextFromUniqueFoodNames(rows.map((r) => r.food_name));
  await db.runAsync('UPDATE MealPlans SET prep_guide = ? WHERE meal_plan_id = ?', [text || null, planId]);
}
